// Sequence & Replay Tests
// ═══════════════════════════════════════════════════════════════════════

describe("createMockModel — sequence replay", () => {
  test("replays configured sequence in order", async () => {
    const mock = createMockModel([
      { object: { step: 1 } },
      { schemaError: "x: expected string" },
      { object: { step: 2 } },
      { apiError: 429 },
      { object: { step: 3 } },
    ]);

    // Step 1: valid
    const [r1] = await callMock(mock);
    expect(r1.object).toEqual({ step: 1 });

    // Step 2: schema error
    try {
      await callMock(mock);
      expect.unreachable("Expected schema error");
    } catch (err) {
      expect(NoObjectGeneratedError.isInstance(err)).toBe(true);
    }

    // Step 3: valid
    const [r3] = await callMock(mock, 1);
    expect(r3.object).toEqual({ step: 2 });

    // Step 4: API error
    try {
      await callMock(mock);
      expect.unreachable("Expected API error");
    } catch (err) {
      expect(APICallError.isInstance(err)).toBe(true);
    }

    // Step 5: valid
    const [r5] = await callMock(mock, 1);
    expect(r5.object).toEqual({ step: 3 });

    // Step 6: exhausted
    try {
      await callMock(mock);
      expect.unreachable("Expected exhaustion");
    } catch (err) {
      expect((err as Error).message).toContain("exhausted");
    }
  });

  test("each call independently tracks the sequence index", async () => {
    const mockA = createMockModel([{ object: { a: 1 } }, { object: { a: 2 } }]);
    const mockB = createMockModel([{ object: { b: 1 } }]);

    const [rA1] = await callMock(mockA);
    expect(rA1.object).toEqual({ a: 1 });

    const [rB1] = await callMock(mockB);
    expect(rB1.object).toEqual({ b: 1 });

    const [rA2] = await callMock(mockA, 1);
    expect(rA2.object).toEqual({ a: 2 });
  });
});

