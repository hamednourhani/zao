describe("createMockModel — delay", () => {
  test("applies specified delay before returning", async () => {
    const mock = createMockModel([{ delay: 100 }]);

    const start = Date.now();
    await callMock(mock);
    const elapsed = Date.now() - start;

    // Bun.sleep(100) should take at least 90ms (allow small variance)
    expect(elapsed).toBeGreaterThanOrEqual(90);
  });

  test("zero delay (delay=0) skips sleep", async () => {
    const mock = createMockModel([{ delay: 0 }]);

    const start = Date.now();
    await callMock(mock);
    const elapsed = Date.now() - start;

    // Should complete quickly (< 50ms)
    expect(elapsed).toBeLessThan(50);
  });

  test("no delay property means no artificial latency", async () => {
    const mock = createMockModel([{}]);

    const start = Date.now();
    await callMock(mock);
    const elapsed = Date.now() - start;

    expect(elapsed).toBeLessThan(50);
  });
});

