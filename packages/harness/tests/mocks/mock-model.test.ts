// Schema Error Tests
// ═══════════════════════════════════════════════════════════════════════

describe("createMockModel — schema errors", () => {
  test("throws NoObjectGeneratedError with full cause chain", async () => {
    const mock = createMockModel([
      { schemaError: "changes.0.file_path: expected string, received number" },
    ]);

    let caught: unknown;
    try {
      await callMock(mock);
    } catch (err) {
      caught = err;
    }

    expect(caught).not.toBeNull();
    // Outer: NoObjectGeneratedError
    expect(NoObjectGeneratedError.isInstance(caught)).toBe(true);
    const nogen = caught as InstanceType<typeof NoObjectGeneratedError>;
    expect(nogen.message).toBe("No object generated");

    // Cause: TypeValidationError
    expect(TypeValidationError.isInstance(nogen.cause)).toBe(true);

    // Root: ZodError with correct path
    const typeErr = nogen.cause as InstanceType<typeof TypeValidationError>;
    expect(typeErr.cause instanceof ZodError).toBe(true);
    const zodErr = typeErr.cause as ZodError;
    expect(zodErr.issues).toHaveLength(1);
    expect(zodErr.issues[0]!.path).toEqual(["changes", 0, "file_path"]);
    expect(zodErr.issues[0]!.message).toBe("expected string, received number");
  });

  test("parses multi-segment paths with numeric indices", async () => {
    const mock = createMockModel([
      { schemaError: "changes.0.content: invalid content type" },
    ]);

    let caught: unknown;
    try {
      await callMock(mock);
    } catch (err) {
      caught = err;
    }

    const nogen = caught as InstanceType<typeof NoObjectGeneratedError>;
    const typeErr = nogen.cause as InstanceType<typeof TypeValidationError>;
    const zodErr = typeErr.cause as ZodError;
    expect(zodErr.issues[0]!.path).toEqual(["changes", 0, "content"]);
  });

  test("parses simple single-segment path", async () => {
    const mock = createMockModel([
      { schemaError: "status: expected string, received null" },
    ]);

    let caught: unknown;
    try {
      await callMock(mock);
    } catch (err) {
      caught = err;
    }

    const nogen = caught as InstanceType<typeof NoObjectGeneratedError>;
    const typeErr = nogen.cause as InstanceType<typeof TypeValidationError>;
    const zodErr = typeErr.cause as ZodError;
    expect(zodErr.issues[0]!.path).toEqual(["status"]);
  });

  test("falls back gracefully when no colon is present in schemaError", async () => {
    // No colon → entire string is used as path, message is "Invalid input"
    const mock = createMockModel([
      { schemaError: "something_went_wrong_without_colon" },
    ]);

    let caught: unknown;
    try {
      await callMock(mock);
    } catch (err) {
      caught = err;
    }

    const nogen = caught as InstanceType<typeof NoObjectGeneratedError>;
    const typeErr = nogen.cause as InstanceType<typeof TypeValidationError>;
    const zodErr = typeErr.cause as ZodError;
    // Path = full string (no colon found, so whole string is pathStr)
    expect(zodErr.issues[0]!.path).toEqual(["something_went_wrong_without_colon"]);
    // Message = "Invalid input" (no colon → fallback)
    expect(zodErr.issues[0]!.message).toBe("Invalid input");
  });

  test("handles schemaError with only a colon (empty path)", async () => {
    const mock = createMockModel([
      { schemaError: ": empty path, only message" },
    ]);

    let caught: unknown;
    try {
      await callMock(mock);
    } catch (err) {
      caught = err;
    }

    const nogen = caught as InstanceType<typeof NoObjectGeneratedError>;
    const typeErr = nogen.cause as InstanceType<typeof TypeValidationError>;
    const zodErr = typeErr.cause as ZodError;
    // Colon at index 0 → path is empty string, parseInt("") = NaN → stays ""
    expect(zodErr.issues[0]!.path).toEqual([""]);
    expect(zodErr.issues[0]!.message).toBe("empty path, only message");
  });

  test("schema error response includes usage metadata", async () => {
    const mock = createMockModel([
      { schemaError: "x: y" },
    ]);

    let caught: unknown;
    try {
      await callMock(mock);
    } catch (err) {
      caught = err;
    }

    const nogen = caught as InstanceType<typeof NoObjectGeneratedError>;
    // Even on error, usage should be available for cost tracking
    expect(nogen.usage).toBeDefined();
    expect(nogen.usage!.inputTokens).toBe(50);
    expect(nogen.usage!.outputTokens).toBe(0);
    expect(nogen.finishReason).toBe("error");
  });
});

