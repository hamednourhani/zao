/**
 * Mock Model Unit Tests — edge case coverage for `createMockModel`.
 *
 * Verifies every code path in the mock model factory:
 * - Valid responses with custom usage/objects
 * - Schema error chain construction (all path formats, no-colon fallback)
 * - API error shapes for all status codes, including timeout (statusCode=undefined)
 * - Exhaustion detection and error message
 * - Captured prompts array behavior
 * - Delay simulation
 * - Default object fallback
 *
 * @module mock-model.test
 */

import { describe, expect, test } from "bun:test";
import { NoObjectGeneratedError } from "ai";
import { APICallError, TypeValidationError } from "@ai-sdk/provider";
import { ZodError } from "zod";
import { createMockModel } from "./mock-model.ts";

// ── Helper: Invoke a mock function with minimal valid params ──────────

function callMock(mockFn: ReturnType<typeof createMockModel>, times = 1) {
  return Promise.all(
    Array.from({ length: times }, () =>
      (mockFn as unknown as Function)({
        prompt: "test prompt",
        model: {},
        schema: {},
      }),
    ),
  );
}

