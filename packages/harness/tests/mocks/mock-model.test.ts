// Happy-Path & Structure Tests
// ═══════════════════════════════════════════════════════════════════════

describe("createMockModel — valid responses", () => {
  test("returns default object when no object is provided", async () => {
    const mock = createMockModel([{}]);
    const [result] = await callMock(mock);

    expect(result.object).toEqual({
      schema_version: "0.1.0",
      status: "success",
      summary: "Task completed successfully.",
      changes: [{ file_path: "output.txt", content: "# Generated by zao" }],
    });
    expect(result.text).toBe(JSON.stringify(result.object));
    expect(result.finishReason).toBe("stop");
  });

  test("returns custom object when provided", async () => {
    const custom = { custom_key: true, nested: { deep: [1, 2, 3] } };
    const mock = createMockModel([{ object: custom }]);
    const [result] = await callMock(mock);

    expect(result.object).toEqual(custom);
    expect(result.text).toBe(JSON.stringify(custom));
  });

  test("response shape matches AI SDK output: usage fields", async () => {
    const mock = createMockModel([{}]);
    const [result] = await callMock(mock);

    // Core usage fields
    expect(typeof result.usage.inputTokens).toBe("number");
    expect(typeof result.usage.outputTokens).toBe("number");
    expect(typeof result.usage.totalTokens).toBe("number");
    expect(result.usage.totalTokens).toBe(
      result.usage.inputTokens + result.usage.outputTokens,
    );

    // Token details (AI SDK v7 shape)
    expect(result.usage.inputTokenDetails).toBeDefined();
    expect(result.usage.outputTokenDetails).toBeDefined();
    expect(typeof result.usage.inputTokenDetails.noCacheTokens).toBe("number");
    expect(typeof result.usage.outputTokenDetails.textTokens).toBe("number");
  });

  test("response shape matches AI SDK output: metadata fields", async () => {
    const mock = createMockModel([{}]);
    const [result] = await callMock(mock);

    expect(result.finishReason).toBe("stop");
    expect(result.warnings).toEqual([]);
    expect(result.response).toBeDefined();
    expect(typeof result.response.id).toBe("string");
    expect(typeof result.response.timestamp).toBe("object"); // Date
    expect(result.response.modelId).toBe("mock-model");
    expect(typeof result.toJsonResponse).toBe("function");
    expect(result.providerMetadata).toBeUndefined();
  });

  test("response IDs are unique across calls", async () => {
    const mock = createMockModel([{}, {}]);
    const [r1, r2] = await callMock(mock, 2);

    expect(r1.response.id).not.toBe(r2.response.id);
    expect(r1.response.id).toBe("mock-resp-1");
    expect(r2.response.id).toBe("mock-resp-2");
  });

  test("uses the provided object as text content (not DEFAULT_OBJECT)", async () => {
    const objs = [
      { a: 1 },
      { b: 2 },
    ];
    const mock = createMockModel([
      { object: objs[0] },
      { object: objs[1] },
    ]);
    const [r1, r2] = await callMock(mock, 2);

    expect(r1.object).toEqual(objs[0]);
    expect(r1.text).toBe(JSON.stringify(objs[0]));
    expect(r2.object).toEqual(objs[1]);
    expect(r2.text).toBe(JSON.stringify(objs[1]));
  });
});

